<?php

declare(strict_types=1);

namespace App\Infrastructure\Pdf;

use App\Domain\Entity\Offer;
use DateTimeImmutable;

/**
 * Dependency-free, deterministic PDF renderer for the immutable offer snapshot.
 *
 * Uses the standard PDF Helvetica fonts with WinAnsiEncoding, so no external
 * binary, browser process or runtime network access is required.
 */
final class OfferPdfGenerator
{
    public function generate(Offer $offer): string
    {
        $snapshot = $offer->pricingSnapshot();
        $lines = [
            ['AUTOFlow MOBILITY', 20, true],
            ['LEASING OFFER', 11, true],
            ['', 10, false],
            ['Offer reference: ' . (string) $offer->id(), 9, false],
            ['Vehicle reference: ' . $snapshot->vehicleId, 9, false],
            ['Quote reference: ' . $snapshot->quoteId, 9, false],
            ['Status: ' . strtoupper($offer->status()->value), 9, true],
            ['Created: ' . $this->date($offer->createdAt()), 9, false],
            ['Valid until: ' . $this->date($offer->expiresAt()), 9, false],
            ['', 10, false],
            ['COMMERCIAL TERMS', 12, true],
            ['Total amount incl. down payment: ' . $this->money($snapshot->totalCostIncludingDownPayment, $snapshot->currency), 10, false],
            ['Down payment: ' . $this->money($this->downPayment($snapshot->totalCostIncludingDownPayment, $snapshot->totalInstallmentsAmount), $snapshot->currency), 10, false],
            ['Monthly instalment: ' . $this->money($snapshot->monthlyAmount, $snapshot->currency), 10, true],
            ['Duration: ' . $snapshot->durationMonths . ' months', 10, false],
            ['Residual value: ' . $this->money($snapshot->residualValue, $snapshot->currency), 10, false],
            ['Annual interest rate: ' . number_format($snapshot->annualInterestRateBasisPoints / 100, 2, '.', '') . ' %', 10, false],
            ['Total instalments: ' . $this->money($snapshot->totalInstallmentsAmount, $snapshot->currency), 10, false],
            ['', 10, false],
            ['CALCULATION', 12, true],
            ['Pricing calculation version: ' . $snapshot->calculationVersion, 9, false],
            ['', 10, false],
            ['This document reflects the pricing snapshot stored with this offer.', 8, false],
            ['It is not a signed contract. The offer remains subject to its stated validity and status.', 8, false],
            ['', 10, false],
            ['Generated by AutoFlow Mobility Platform', 8, false],
        ];

        $stream = "BT\n";
        $y = 790;
        foreach ($lines as [$text, $size, $bold]) {
            if ($text === '') {
                $y -= 12;
                continue;
            }

            $font = $bold ? '/F2' : '/F1';
            $stream .= sprintf("%s %d Tf 1 0 0 1 54 %d Tm (%s) Tj\n", $font, $size, $y, $this->escapeText($text));
            $y -= $size + 10;
        }
        $stream .= "ET\n";

        return $this->document($stream);
    }

    private function document(string $content): string
    {
        $objects = [
            '<< /Type /Catalog /Pages 2 0 R >>',
            '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
            '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>',
            '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>',
            '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>',
            '<< /Length ' . strlen($content) . " >>\nstream\n" . $content . "endstream",
        ];

        $pdf = "%PDF-1.4\n%\xE2\xE3\xCF\xD3\n";
        $offsets = [0];
        foreach ($objects as $index => $object) {
            $offsets[] = strlen($pdf);
            $pdf .= ($index + 1) . " 0 obj\n" . $object . "\nendobj\n";
        }

        $xrefOffset = strlen($pdf);
        $pdf .= "xref\n0 " . (count($objects) + 1) . "\n";
        $pdf .= "0000000000 65535 f \n";
        foreach (array_slice($offsets, 1) as $offset) {
            $pdf .= sprintf("%010d 00000 n \n", $offset);
        }
        $pdf .= "trailer\n<< /Size " . (count($objects) + 1) . " /Root 1 0 R >>\n";
        $pdf .= "startxref\n" . $xrefOffset . "\n%%EOF";

        return $pdf;
    }

    private function escapeText(string $value): string
    {
        $encoded = mb_convert_encoding($value, 'Windows-1252', 'UTF-8');

        return str_replace(['\\', '(', ')', "\r", "\n"], ['\\\\', '\\(', '\\)', '', ' '], $encoded);
    }

    private function date(DateTimeImmutable $date): string
    {
        return $date->format('d.m.Y H:i T');
    }

    private function money(string $amount, string $currency): string
    {
        return number_format((float) $amount, 2, ',', '.') . ' ' . $currency;
    }

    private function downPayment(string $total, string $instalments): string
    {
        return number_format((float) $total - (float) $instalments, 2, '.', '');
    }
}
