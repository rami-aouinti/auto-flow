<?php

declare(strict_types=1);

namespace AutoFlow\Notification\Infrastructure\Pdf;

use AutoFlow\Notification\Domain\Notification\OfferPublishedNotification;

final class OfferPdfGenerator
{
    public function generate(OfferPublishedNotification $notification): string
    {
        $p = $notification->pricing;
        $lines = [
            ['AUTOFLOW MOBILITY', 20, true],
            ['LEASING OFFER', 11, true],
            ['', 10, false],
            ['Offer reference: ' . $notification->offerId, 9, false],
            ['Vehicle reference: ' . $notification->vehicleId, 9, false],
            ['Quote reference: ' . $notification->quoteId, 9, false],
            ['Status: PUBLISHED', 9, true],
            ['Valid until: ' . $notification->expiresAt, 9, false],
            ['', 10, false],
            ['COMMERCIAL TERMS', 12, true],
            ['Total amount incl. down payment: ' . $this->money((string) $p['totalCostIncludingDownPayment'], (string) $p['currency']), 10, false],
            ['Down payment: ' . $this->money(number_format((float) $p['totalCostIncludingDownPayment'] - (float) $p['totalInstallmentsAmount'], 2, '.', ''), (string) $p['currency']), 10, false],
            ['Monthly instalment: ' . $this->money((string) $p['monthlyAmount'], (string) $p['currency']), 10, true],
            ['Duration: ' . (int) $p['durationMonths'] . ' months', 10, false],
            ['Residual value: ' . $this->money((string) $p['residualValue'], (string) $p['currency']), 10, false],
            ['Annual interest rate: ' . number_format(((int) $p['annualInterestRateBasisPoints']) / 100, 2, '.', '') . ' %', 10, false],
            ['Total instalments: ' . $this->money((string) $p['totalInstallmentsAmount'], (string) $p['currency']), 10, false],
            ['', 10, false],
            ['Pricing calculation version: ' . (string) $p['calculationVersion'], 9, false],
            ['', 10, false],
            ['This document reflects the immutable pricing snapshot stored with the published offer.', 8, false],
            ['It is not a signed contract and remains subject to the offer validity and status.', 8, false],
            ['', 10, false],
            ['Generated by AutoFlow Mobility Platform', 8, false],
        ];

        $stream = "BT\n";
        $y = 790;
        foreach ($lines as [$text, $size, $bold]) {
            if ($text === '') {
                $y -= 12;
                continue;
            }
            $stream .= sprintf("%s %d Tf 1 0 0 1 54 %d Tm (%s) Tj\n", $bold ? '/F2' : '/F1', $size, $y, $this->escapeText($text));
            $y -= $size + 10;
        }
        $stream .= "ET\n";

        return $this->document($stream);
    }

    private function document(string $content): string
    {
        $objects = [
            '<< /Type /Catalog /Pages 2 0 R >>',
            '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
            '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>',
            '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>',
            '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>',
            '<< /Length ' . strlen($content) . " >>\nstream\n" . $content . "endstream",
        ];
        $pdf = "%PDF-1.4\n%\xE2\xE3\xCF\xD3\n";
        $offsets = [0];
        foreach ($objects as $index => $object) {
            $offsets[] = strlen($pdf);
            $pdf .= ($index + 1) . " 0 obj\n" . $object . "\nendobj\n";
        }
        $xref = strlen($pdf);
        $pdf .= "xref\n0 " . (count($objects) + 1) . "\n0000000000 65535 f \n";
        foreach (array_slice($offsets, 1) as $offset) {
            $pdf .= sprintf("%010d 00000 n \n", $offset);
        }
        $pdf .= "trailer\n<< /Size " . (count($objects) + 1) . " /Root 1 0 R >>\nstartxref\n" . $xref . "\n%%EOF";

        return $pdf;
    }

    private function escapeText(string $value): string
    {
        $encoded = mb_convert_encoding($value, 'Windows-1252', 'UTF-8');

        return str_replace(['\\', '(', ')', "\r", "\n"], ['\\\\', '\\(', '\\)', '', ' '], $encoded);
    }

    private function money(string $amount, string $currency): string
    {
        return number_format((float) $amount, 2, ',', '.') . ' ' . $currency;
    }
}